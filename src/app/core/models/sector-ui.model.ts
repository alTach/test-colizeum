/**
 * Интерфейс представления сектора на колесе фортуны для SVG-отрисовки.
 * Вынесен в отдельный файл моделей согласно требованиям.
 */
export interface SectorUi {
  /** Уникальный идентификатор приза в секторе */
  id: number;
  /** Текстовое описание приза */
  label: string;
  /** Эмодзи-иконка приза */
  icon: string;
  /** SVG-путь (d-атрибут) для отрисовки сектора (pie piece) */
  pathD: string;
  /** Флаг золотого (альтернативного) сектора для чередования цветов */
  isGold: boolean;
  /** CSS transform строка для позиционирования и вращения текста приза */
  textTransform: string;
  /** Координата X базовой точки иконки */
  baseX: number;
  /** Координата Y базовой точки иконки */
  baseY: number;
  /** Координата X точки-украшения на ободе колеса */
  dotX: number;
  /** Координата Y точки-украшения на ободе колеса */
  dotY: number;
}
